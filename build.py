#!/usr/bin/env python3
"""Generate the talk listings in index.html and the calendar files from talks.json.

Usage: python3 build.py

Rewrites the region of index.html between the TALKS:START / TALKS:END markers,
and writes calendar/<id>.ics for each talk plus calendar/all-talks.ics.
Uses only the Python standard library (3.9+).
"""

import html
import json
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlencode
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parent
SERIES = "CS Futures in the Age of AI"
START_MARK = "<!-- TALKS:START (generated by build.py; edit talks.json instead) -->"
END_MARK = "<!-- TALKS:END -->"


def load():
    data = json.loads((ROOT / "talks.json").read_text(encoding="utf-8"))
    tz = ZoneInfo(data["timezone"])
    for t in data["talks"]:
        t["start_dt"] = datetime.fromisoformat(f"{t['date']}T{t['start']}").replace(tzinfo=tz)
        t["end_dt"] = datetime.fromisoformat(f"{t['date']}T{t['end']}").replace(tzinfo=tz)
    data["talks"].sort(key=lambda t: t["start_dt"])
    return data


def fmt_time(dt):
    s = dt.strftime("%I:%M").lstrip("0")
    return s


def fmt_when(t):
    s, e = t["start_dt"], t["end_dt"]
    date = f"{s.strftime('%A, %B')} {s.day}, {s.year}"
    s_ampm, e_ampm = s.strftime("%p").lower(), e.strftime("%p").lower()
    if s_ampm == e_ampm:
        times = f"{fmt_time(s)}–{fmt_time(e)} {e_ampm}"
    else:
        times = f"{fmt_time(s)} {s_ampm} – {fmt_time(e)} {e_ampm}"
    return date, times


def description(t, site_url):
    return f"{SERIES} seminar series, hosted by the CS AI Council.\nSpeaker: {t['speaker']}\n{site_url}"


def utc_stamp(dt):
    return dt.astimezone(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def google_url(t, data):
    q = {
        "action": "TEMPLATE",
        "text": f"{t['speaker']}: {t['title']}",
        "dates": f"{utc_stamp(t['start_dt'])}/{utc_stamp(t['end_dt'])}",
        "details": description(t, data["site_url"]),
        "location": data["location"],
        "ctz": data["timezone"],
    }
    return "https://calendar.google.com/calendar/render?" + urlencode(q)


def outlook_url(t, data):
    q = {
        "path": "/calendar/action/compose",
        "rru": "addevent",
        "subject": f"{t['speaker']}: {t['title']}",
        "startdt": t["start_dt"].isoformat(),
        "enddt": t["end_dt"].isoformat(),
        "body": description(t, data["site_url"]),
        "location": data["location"],
    }
    return "https://outlook.office.com/calendar/0/deeplink/compose?" + urlencode(q)


def ics_escape(s):
    return s.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,").replace("\n", "\\n")


def ics_fold(line):
    """Fold lines longer than 75 octets per RFC 5545."""
    out, cur = [], b""
    for ch in line:
        b = ch.encode("utf-8")
        if len(cur) + len(b) > (75 if not out else 74):
            out.append(cur.decode("utf-8"))
            cur = b""
        cur += b
    out.append(cur.decode("utf-8"))
    return "\r\n ".join(out)


def ics_event(t, data, stamp):
    lines = [
        "BEGIN:VEVENT",
        f"UID:{t['id']}@cs-futures-ai.wisc.edu",
        f"DTSTAMP:{stamp}",
        f"DTSTART:{utc_stamp(t['start_dt'])}",
        f"DTEND:{utc_stamp(t['end_dt'])}",
        f"SUMMARY:{ics_escape(t['speaker'] + ': ' + t['title'])}",
        f"DESCRIPTION:{ics_escape(description(t, data['site_url']))}",
        f"LOCATION:{ics_escape(data['location'])}",
        f"URL:{data['site_url']}",
        "END:VEVENT",
    ]
    return lines


def ics_calendar(events, name):
    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//UW-Madison CS//CS Futures in the Age of AI//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        f"X-WR-CALNAME:{ics_escape(name)}",
    ]
    for ev in events:
        lines += ev
    lines.append("END:VCALENDAR")
    return "\r\n".join(ics_fold(l) for l in lines) + "\r\n"


def write_ics(path, text):
    """Write only if something other than the DTSTAMP line changed, to avoid noisy commits."""
    def strip(x):
        return "\n".join(l for l in x.splitlines() if not l.startswith("DTSTAMP:"))
    if path.exists() and strip(path.read_text(encoding="utf-8")) == strip(text):
        return
    path.write_bytes(text.encode("utf-8"))


def talk_html(t, data):
    e = html.escape
    date, times = fmt_when(t)
    speaker = e(t["speaker"])
    if t.get("speaker_url"):
        speaker = f'<a href="{e(t["speaker_url"])}">{speaker}</a>'
    affil = f', <span class="affil">{e(t["affiliation"])}</span>' if t.get("affiliation") else ""
    abstract = ""
    if t.get("abstract"):
        abstract = f"""
        <details>
          <summary>Abstract</summary>
          <p>{e(t["abstract"])}</p>
        </details>"""
    return f"""      <article class="talk" id="{e(t['id'])}" data-end="{t['end_dt'].isoformat()}">
        <p class="talk-date">{e(date)} · <span class="talk-time">{e(times)}</span></p>
        <h3 class="talk-title">{e(t['title'])}</h3>
        <p class="talk-speaker">{speaker}{affil}</p>{abstract}
        <p class="add-to-cal">Add to calendar:
          <a href="calendar/{e(t['id'])}.ics" download>Apple / iCal (.ics)</a>
          <a href="{e(google_url(t, data))}" target="_blank" rel="noopener">Google</a>
          <a href="{e(outlook_url(t, data))}" target="_blank" rel="noopener">Outlook</a>
        </p>
      </article>"""


def main():
    data = load()
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")

    cal_dir = ROOT / "calendar"
    cal_dir.mkdir(exist_ok=True)
    keep = {f"{t['id']}.ics" for t in data["talks"]} | {"all-talks.ics"}
    for old in cal_dir.glob("*.ics"):
        if old.name not in keep:
            old.unlink()
    all_events = []
    for t in data["talks"]:
        ev = ics_event(t, data, stamp)
        all_events.append(ev)
        write_ics(cal_dir / f"{t['id']}.ics", ics_calendar([ev], SERIES))
    write_ics(cal_dir / "all-talks.ics", ics_calendar(all_events, SERIES))

    index = ROOT / "index.html"
    page = index.read_text(encoding="utf-8")
    i, j = page.index(START_MARK), page.index(END_MARK)
    body = "\n".join(talk_html(t, data) for t in data["talks"])
    page = page[: i + len(START_MARK)] + "\n" + body + "\n      " + page[j:]
    index.write_text(page, encoding="utf-8")
    print(f"Wrote {len(data['talks'])} talks to index.html and calendar/*.ics")


if __name__ == "__main__":
    main()
